#!/usr/bin/env bash
# Build the release APK entirely on this machine, without an Expo/EAS account.
#
# Why this exists
#   build/build_apk.sh needs `eas login` and an EAS projectId. This script does the
#   same job with the Android SDK, JDK 17 and Gradle, so the APK can be produced
#   offline from the repository alone.
#
# Prerequisites
#   - JDK 17 on PATH (or JAVA_HOME set)
#   - Android SDK with build-tools, platform 35 and NDK 27.1.12297006
#     (`sdkmanager "platform-tools" "platforms;android-35" "build-tools;35.0.0"`)
#   - ANDROID_HOME pointing at the SDK
#
# Usage
#   bash build/build_apk_local.sh
#   ANDROID_HOME=/opt/android-sdk bash build/build_apk_local.sh
#
# Notes
#   - Only arm64-v8a is built by default: it covers every current Android phone
#     and keeps the build inside ~2.5 GB of heap. Override with
#       ABI="arm64-v8a,armeabi-v7a" bash build/build_apk_local.sh
#   - `mobile/android/` is generated by `expo prebuild` and is gitignored, so this
#     script regenerates it when missing.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MOBILE="$ROOT/mobile"
BUILD_DIR="$ROOT/build"
ABI="${ABI:-arm64-v8a}"

GROUP_CODE="$(python3 - "$MOBILE/app.json" <<'PY'
import json, sys
with open(sys.argv[1], encoding="utf-8") as handle:
    print(json.load(handle)["expo"]["extra"]["groupCode"])
PY
)"
APK_NAME="AgriSokoPocket_${GROUP_CODE}.apk"

if [ "$GROUP_CODE" = "GXX" ]; then
  echo "WARNING: app.json still uses the placeholder group code GXX." >&2
fi

if [ -z "${ANDROID_HOME:-}" ] && [ -z "${ANDROID_SDK_ROOT:-}" ]; then
  echo "ERROR: set ANDROID_HOME to your Android SDK before running this script." >&2
  exit 1
fi
export ANDROID_HOME="${ANDROID_HOME:-$ANDROID_SDK_ROOT}"
export ANDROID_SDK_ROOT="$ANDROID_HOME"

cd "$MOBILE"

if [ ! -d android ]; then
  echo "No native project found, running expo prebuild..."
  npx expo prebuild --platform android --no-install
fi

echo "sdk.dir=$ANDROID_HOME" > android/local.properties

# Keep peak memory inside what a 6.6 GB laptop can hold: one worker, no parallel
# projects, a 2 GB daemon heap and an in-process Kotlin compiler. Written into
# the generated gradle.properties, which is gitignored, so the repository stays
# free of machine-specific settings.
python3 - android/gradle.properties <<'PY'
import sys

path = sys.argv[1]
with open(path, encoding="utf-8") as handle:
    text = handle.read()

wanted = {
    "org.gradle.jvmargs": "-Xmx2048m -XX:MaxMetaspaceSize=512m",
    "org.gradle.parallel": "false",
    "org.gradle.workers.max": "1",
    "kotlin.compiler.execution.strategy": "in-process",
}

lines = []
seen = set()
for line in text.splitlines():
    key = line.split("=", 1)[0].strip()
    if key in wanted:
        lines.append(f"{key}={wanted[key]}")
        seen.add(key)
    else:
        lines.append(line)
for key, value in wanted.items():
    if key not in seen:
        lines.append(f"{key}={value}")

with open(path, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines) + "\n")
PY

echo "Building release APK for group $GROUP_CODE (ABI: $ABI)..."
(
  cd android
  ./gradlew assembleRelease --no-daemon --console=plain \
    --no-parallel --max-workers=1 \
    -PreactNativeArchitectures="$ABI"
)

SOURCE_APK="$(ls -t android/app/build/outputs/apk/release/*.apk 2>/dev/null | head -1 || true)"
[ -n "$SOURCE_APK" ] || { echo "ERROR: no APK produced by Gradle" >&2; exit 1; }

mkdir -p "$BUILD_DIR"
cp "$SOURCE_APK" "$BUILD_DIR/$APK_NAME"

# Gradle signs the release build with the debug certificate, which is fine for
# `adb install` but is not a release identity. If a private keystore is available,
# re-sign with it. The keystore is deliberately kept outside the repository.
KEYSTORE="${AGRISOKO_KEYSTORE:-$HOME/.agrisoko-keys/agrisoko-release.jks}"
BT="$(ls -d "${ANDROID_HOME}"/build-tools/*/ 2>/dev/null | sort -V | tail -1)"
if [ -f "$KEYSTORE" ] && [ -n "$BT" ] && [ -x "${BT}apksigner" ]; then
  if [ -z "${AGRISOKO_KEY_PASS:-}" ]; then
    echo "ERROR: AGRISOKO_KEY_PASS is not set; cannot open $KEYSTORE" >&2
    echo "       Re-run with: AGRISOKO_KEY_PASS=<password> bash build/build_apk_local.sh" >&2
    exit 1
  fi
  echo "Signing with release keystore $KEYSTORE ..."
  "${BT}apksigner" sign --ks "$KEYSTORE" --ks-key-alias "${AGRISOKO_KEY_ALIAS:-agrisoko}" \
    --ks-pass "pass:$AGRISOKO_KEY_PASS" --key-pass "pass:$AGRISOKO_KEY_PASS" \
    "$BUILD_DIR/$APK_NAME"
  "${BT}apksigner" verify "$BUILD_DIR/$APK_NAME"
  echo "Signature verified."
else
  echo "No release keystore at $KEYSTORE; the APK stays in its Gradle debug-signed form." >&2
fi

ls -lh "$BUILD_DIR/$APK_NAME"
echo
echo "APK ready: build/$APK_NAME"
echo "SHA-256: $(sha256sum "$BUILD_DIR/$APK_NAME" | cut -d' ' -f1)"
echo "Attach this exact file to the GitHub v1.0.0 release."
